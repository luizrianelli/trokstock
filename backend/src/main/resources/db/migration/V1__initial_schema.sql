create table product (
    id bigint generated by default as identity primary key,
    sku varchar(40) not null unique,
    name varchar(120) not null,
    price numeric(12,2) not null check (price >= 0),
    stock integer not null check (stock >= 0)
);
create table customer (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    email varchar(180) not null unique
);
create table sales_order (
    id bigint generated by default as identity primary key,
    customer_id bigint not null references customer,
    status varchar(16) not null check (status in ('DRAFT', 'CONFIRMED', 'CANCELED')),
    created_at timestamptz not null,
    total numeric(20,2) not null check (total >= 0)
);
create table order_line (
    id bigint generated by default as identity primary key,
    order_id bigint not null references sales_order,
    product_id bigint not null references product,
    quantity integer not null check (quantity > 0),
    unit_price numeric(12,2) not null check (unit_price >= 0),
    unique(order_id, product_id)
);
create table movement (
    id bigint generated by default as identity primary key,
    product_id bigint not null references product,
    order_id bigint references sales_order,
    kind varchar(16) not null check (kind in ('ENTRY','SALE','RETURN')),
    quantity integer not null check (quantity > 0),
    created_at timestamptz not null
);
create index movement_product_idx on movement(product_id, id desc);
create index sales_order_status_idx on sales_order(status);
